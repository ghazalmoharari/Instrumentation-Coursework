// External Interrupt Callback (Counts Pulses on PA2)
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin) {

    // --- PART 2: Optocounter on PA2 ---
    if (GPIO_Pin == GPIO_PIN_2) {
        pulse_count++;
    }

    // --- PART 3: Encoder on PA5 and PA6 ---
    if (GPIO_Pin == GPIO_PIN_5 || GPIO_Pin == GPIO_PIN_6) {
        uint8_t state_A = HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_5);
        uint8_t state_B = HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_6);

        // Interrupt on Channel A (PA5)
        if (GPIO_Pin == GPIO_PIN_5) {
            if (state_A == state_B) { encoder_ticks++; ticks_per_sec++; }
            else { encoder_ticks--; ticks_per_sec--; }
        }

        // Interrupt on Channel B (PA6)
        if (GPIO_Pin == GPIO_PIN_6) {
            if (state_A != state_B) { encoder_ticks++; ticks_per_sec++; }
            else { encoder_ticks--; ticks_per_sec--; }
        }
    }
}

// Merged Timer Callback (Calculates both RPMs every 1 second)
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim) {
    if (htim->Instance == TIM3) {

        // --- PART 2 Math ---
        rpm = ((float)pulse_count * 60.0) / (float)N_VALUE;
        pulse_count = 0;

        // Optocounter LED Warning on PA4
        if (rpm > 500.0) {
            HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_4);
        } else {
            HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_RESET);
        }

        // --- PART 3 Math ---
        float tps = (ticks_per_sec < 0) ? -ticks_per_sec : ticks_per_sec;
        enc_rpm = (tps * 60.0) / (4.0 * PPR_VALUE);
        ticks_per_sec = 0;

        // Trigger Display Update
        update_display = 1;
    }
}
