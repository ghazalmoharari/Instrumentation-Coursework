	        // PART B: IR Proximity Sensor Reading
	        // =========================================================

	        // Read the state of the IR sensor OUT pin (PA2)
	        // LOW (RESET) usually means an object is reflecting the IR light
	        GPIO_PinState ir_state = HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_2);


	        // =========================================================
	        // Update the LCD Display
	        // =========================================================
	        Lcd_clear(&lcd);

	        // Top Row: Print Ultrasonic Distance
	        sprintf(lcd_buffer, "Dist: %d cm", distance);
	        Lcd_cursor(&lcd, 0, 0);
	        Lcd_string(&lcd, lcd_buffer);

	        // Bottom Row: Print IR Sensor Status
	        Lcd_cursor(&lcd, 1, 0);
	        if (ir_state == GPIO_PIN_RESET) {
	            Lcd_string(&lcd, "Object Detected!");
	        } else {
	            Lcd_string(&lcd, "Path Clear");
	        }

	        HAL_Delay(250); // Delay for LCD stability and simulation pacing

	      /* USER CODE END WHILE */


    /* USER CODE BEGIN 3 */
