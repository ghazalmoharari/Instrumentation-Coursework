	        // 1. Send a 15us pulse to Trigger (PA0)
	        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_0, GPIO_PIN_SET);
	        delay_us(15);
	        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_0, GPIO_PIN_RESET);

	        // 2. Wait for Echo pin (PA1) to go HIGH with timeout
	        uint32_t wait_timeout = 60000;
	        while (!(HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_1)) && wait_timeout-- > 0);

	        // 3. Measure how long Echo pin stays HIGH using the Hardware Timer
	        __HAL_TIM_SET_COUNTER(&htim1, 0);
	        while (HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_1) && __HAL_TIM_GET_COUNTER(&htim1) < 50000);

	        // 4. Get the exact microsecond time
	        local_time = __HAL_TIM_GET_COUNTER(&htim1);

	        // 5. Calculate Distance using Proteus CAL factor (58)
	        if (local_time >= 50000 || wait_timeout == 0) {
	            distance = 0;
	        } else {
	            distance = local_time / 58;
	        }

